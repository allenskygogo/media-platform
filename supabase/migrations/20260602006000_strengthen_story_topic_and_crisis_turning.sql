-- Strengthen story topic generation and story script crisis/turning-point rules.
-- This keeps the AI aligned with the course SOP when ai_agents overrides Worker defaults.

update public.ai_agents
set
  system_prompt = system_prompt || $$

【說故事選題補充規則】
當 input.scriptType = "story" 或腳本類型為說故事時，選題一定要圍繞三種素材之一：
1. 自己達成的成就。
2. 你幫別人達成的成就。
3. 你用價值觀解決的衝突事件。
禁止產生知識解析、技巧清單、普通觀點或泛泛經驗談。說故事選題必須能自然接出困境與轉機。
$$,
  user_prompt_template = replace(
    user_prompt_template,
    '- 不要使用 emoji',
    $$
- 如果 input.scriptType = "story"，請嚴格依照以下流程產生選題：
  1. 先判斷素材屬於哪一種故事：小有成就、成功案例、平凡英雄。
  2. 小有成就選題必須是「我達成了什麼成果」加上一個阻礙或代價，不可只寫心得。
  3. 成功案例選題必須是「我幫別人達成什麼成果」，並且能看出你介入幫助與對方努力。
  4. 平凡英雄選題必須是「我遇到或看見什麼衝突」，以及你用價值觀做了什麼行動。
  5. 每個選題都要能接出至少一輪困境與轉機，最好能接出兩輪：困難1、轉機1、困難2、轉機2。
- 說故事選題模板可使用：
  - 沒想到我一個【身份】，靠【事情】做到【成果】，只不過【阻礙】
  - 我幫一個【對象】，從【低點】做到【成果】，中間差點卡在【困境】
  - 那天我遇到【不公平事件】，我沒有選擇【常見反應】，而是【行動】
  - 做【主題】最狼狽的那一年，我以為自己快撐不下去了
- 說故事禁止輸出：
  - 如何做好【主題】
  - 【主題】技巧解析
  - 【主題】方法教學
  - 我對【主題】的一個看法
  - 沒有明確主角、成果、衝突、困境或轉機的題目
- 不要使用 emoji$$
  ),
  updated_at = now()
where feature_key = 'topics';

update public.ai_agents
set
  system_prompt = system_prompt || $$

【說故事腳本補充規則】
故事選題與腳本一定要圍繞自己達成的成就、你幫別人達成的成就，或你用價值觀解決的衝突事件；困境與轉機優先寫成兩輪：困難1、轉機1、困難2、轉機2。
$$,
  user_prompt_template = replace(
    user_prompt_template,
    '- generate_script 必須參考知識庫腳本句式，不要使用通用模板；知識庫 PDF 是生成依據，不只是 evaluate_practice 的判斷依據。',
    $$
- 說故事補充硬規則：
  1. 故事選題與腳本都必須圍繞三種素材之一：自己達成的成就、你幫別人達成的成就、你用價值觀解決的衝突事件。
  2. 小有成就和成功案例都要先有明確成果，再補上阻礙；沒有阻礙，故事不成立。
  3. 【成就或衝突事件】第一句要像短影音開場，例如「沒想到我一個___，靠___做到___，只不過___」、「我幫一個___，從___做到___，中間差點卡在___」、「那天我遇到___，我沒有選擇___，而是___」。
  4. 【困境與轉機】優先寫成「困難1（橋段名）→轉機1（橋段名）→困難2（橋段名）→轉機2（橋段名）」。
  5. 可用困境橋段：盲目自信、家門不幸、天災人禍、惡霸欺壓、過河拆橋、至親背叛、強權干涉。
  6. 可用轉機橋段：通關密碼、至情激活、天賦異稟、意外之喜、以和德服、貴人相助、韜光養晦。
  7. 每個困境與轉機都要有具體畫面、人物、事件、代價或結果，不可只寫「遇到困難，後來找到方法」。
  8. 禁止寫成知識解析、觀點評論、技巧清單、泛泛經驗談或雞湯。
- generate_script 必須參考知識庫腳本句式，不要使用通用模板；知識庫 PDF 是生成依據，不只是 evaluate_practice 的判斷依據.$$
  ),
  updated_at = now()
where feature_key = 'script';
